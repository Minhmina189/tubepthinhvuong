def get_price(product_key: str, size: str, length: int = None, material: str = None) -> float | None:
    """
    Tra giá sản phẩm.
    product_key: mã sản phẩm nội bộ
    size: ví dụ 'M8', 'M10'
    length: chiều dài mm (cho vít/bulong), None cho ECU/LDP/LDV
    material: 'ECU', 'LDP', 'LDV' hoặc None
    """
    table = PRODUCT_TABLES.get(product_key)
    if table is None:
        return None
    size_data = table.get(size)
    if size_data is None:
        return None

    if isinstance(size_data, dict):
        if material in ("ECU", "LDP", "LDV"):
            return size_data.get(material)
        if length is not None:
            return size_data.get(length)
        return None
    else:
        return size_data  # scalar price (e.g. for standalone ECU tables)


